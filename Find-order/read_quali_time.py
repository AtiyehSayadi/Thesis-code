import numpy as np
import missing_gp_quali  # change this name
import re


def parse_matrices_from_file(filepath):
    matrices = []

    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Split by "Matrix X:"
    blocks = re.split(r"Matrix \d+:", content)

    for block in blocks:
        lines = block.strip().split("\n")

        if not lines or lines == ['']:
            continue

        matrix = []
        for line in lines:
            row = line.strip().split()
            matrix.append(row)

        matrices.append(np.array(matrix, dtype=object))

    return matrices


def run_all_matrices(filepath):
    matrices = parse_matrices_from_file(filepath)

    execution_times = []

    for idx, mat in enumerate(matrices):
        print(f"Running Matrix {idx+1}...")

        _, time_ms = missing_gp_quali.find_missing_multiple(mat)
        execution_times.append(time_ms)

    print("\nExecution times (ms):")
    print(np.array(execution_times))

    return execution_times


