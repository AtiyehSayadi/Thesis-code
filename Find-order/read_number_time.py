import numpy as np
import re
from missing_gp_number import find_missing_multiple  # change this


def parse_matrices(filepath):
    matrices = []

    with open(filepath, "r") as f:
        content = f.read()

    blocks = re.split(r"Matrix \d+:", content)

    for block in blocks:
        lines = block.strip().split("\n")

        if not lines or lines == ['']:
            continue

        matrix = []
        for line in lines:
            row = []
            for val in line.split():
                if val == "?":
                    row.append("?")
                else:
                    row.append(float(val))
            matrix.append(row)

        matrices.append(np.array(matrix, dtype=object))

    return matrices


def run_all(filepath):
    matrices = parse_matrices(filepath)

    execution_times = []

    for i, mat in enumerate(matrices):
        print(f"Running Matrix {i+1}...")

        _, time_ms = find_missing_multiple(mat)
        execution_times.append(time_ms)

    execution_times = np.array(execution_times)

    print("\nFinal Execution Times (ms):")
    print(execution_times)

    return execution_times


